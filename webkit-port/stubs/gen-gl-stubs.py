"""Generate EGL / OpenGL ES entry points from Khronos headers.

Usage: gen-gl-stubs.py <sdk-include-dir> <out-dir>

WebKit's PlayStation port compiles the TextureMapper / CoordinatedGraphics
code unconditionally, so it references EGL and GLES entry points. Each one
generated here forwards to Sony's GLES library (libSceGLSlimVSH) once the
shell has started it in this process (src/ps5/glslim: ps5_glslim_proc(),
linked weakly). Until then, and in processes that never start it, every call
fails as a stub: EGL_NO_DISPLAY, EGL_FALSE, NULL, eglGetError() ==
EGL_NOT_INITIALIZED; GLES calls do nothing and return 0.
"""
import os
import re
import sys

inc, out = sys.argv[1], sys.argv[2]

PROTO = re.compile(
    r"^(?:EGLAPI|GL_APICALL)\s+(?P<ret>[\w\s\*]+?)\s*(?:EGLAPIENTRY|GL_APIENTRY)\s+"
    r"(?P<name>\w+)\s*\((?P<args>[^;]*)\)\s*;", re.M)


def collect(headers):
    seen, protos = set(), []
    for h in headers:
        text = open(os.path.join(inc, h)).read()
        text = re.sub(r"\s*\n\s*", " ", text)  # join wrapped prototypes
        text = re.sub(r"\b(EGLAPI|GL_APICALL)\b", r"\n\1", text)
        for m in PROTO.finditer(text):
            name = m.group("name")
            if name in seen:
                continue
            seen.add(name)
            protos.append((m.group("ret").strip(), name, m.group("args").strip()))
    return protos


def body(ret, name):
    if ret == "void":
        return ""
    if name == "eglGetError":
        return "    return EGL_NOT_INITIALIZED;\n"
    if ret in ("EGLBoolean", "GLboolean"):
        return "    return 0;\n"
    return "    return (%s)0;\n" % ret


def arg_names(args):
    if not args or args.strip() == "void":
        return []
    names = []
    for part in args.split(","):
        part = re.sub(r"\[[^\]]*\]", "", part).strip()
        m = re.search(r"(\w+)\s*$", part)
        names.append(m.group(1))
    return names


PREAMBLE = """
void* ps5_glslim_proc(const char* name) __attribute__((weak));

static void* ps5_gl_resolve(const char* name)
{
    return ps5_glslim_proc ? ps5_glslim_proc(name) : (void*)0;
}
"""


def emit(path, includes, protos):
    with open(path, "w", newline="\n") as f:
        f.write("// SPDX-License-Identifier: GPL-3.0-or-later\n")
        f.write("// Generated by gen-gl-stubs.py. Do not edit.\n\n")
        for d in includes:
            f.write(d + "\n")
        f.write(PREAMBLE + "\n")
        for ret, name, args in protos:
            names = arg_names(args)
            args = args or "void"
            call = "real(%s)" % ", ".join(names)
            if ret == "void":
                forward = "        %s;\n        return;\n" % call
            else:
                forward = "        return %s;\n" % call
            f.write("%s %s(%s)\n{\n"
                    "    static __typeof__(&%s) real;\n"
                    "    if (!real)\n"
                    "        real = (__typeof__(&%s))ps5_gl_resolve(\"%s\");\n"
                    "    if (real) {\n%s    }\n%s}\n\n"
                    % (ret, name, args, name, name, name, forward, body(ret, name)))


egl = collect(["EGL/egl.h", "EGL/eglext.h"])
emit(os.path.join(out, "egl_stub.c"),
     ["#define EGL_EGLEXT_PROTOTYPES 1", "#include <EGL/egl.h>", "#include <EGL/eglext.h>"], egl)

gles = collect(["GLES3/gl3.h", "GLES2/gl2.h", "GLES2/gl2ext.h"])
emit(os.path.join(out, "glesv2_stub.c"),
     ["#define GL_GLEXT_PROTOTYPES 1", "#include <GLES3/gl3.h>", "#include <GLES2/gl2ext.h>"], gles)

print("egl: %d functions, gles: %d functions" % (len(egl), len(gles)))
